#!/usr/bin/env bash
# Build "dist/PQ1 Demo.command": one double-clickable file for Apple Silicon and Intel Macs.
#
#   ./build.sh            needs cc, zig (or ZIG=/path/to/zig), xxd, base64, zip
#
# The ERC-20 proofs and the golden requests come from ../android-demo, so the two demos cannot
# drift: the host build has to pass --selftest against the Android goldens before anything is
# packaged. zig cross-compiles the macOS binaries without an SDK (the program dlopens IOKit).
set -euo pipefail
cd "$(dirname "$0")"
ZIG=${ZIG:-zig}
ANDROID=../android-demo/app/src
CFLAGS=(-std=gnu11 -Wall -Wextra -Werror -Ibuild)
mkdir -p build dist

# 1. The ERC-20 proofs (cut by android-demo/tools/gen_assets.py), as a C table.
{
  echo "/* Generated by build.sh from android-demo/app/src/main/assets/erc20. Do not edit. */"
  rows=()
  for f in "$ANDROID"/main/assets/erc20/*.bin; do
    name=$(basename "$f" .bin) # <chain>_<token>
    echo "static const unsigned char proof_$name[] = {"
    xxd -i <"$f"
    echo "};"
    rows+=("{ ${name%%_*}, \"${name#*_}\", proof_$name, sizeof proof_$name },")
  done
  echo "static const struct proof PROOFS[] = {"
  printf '    %s\n' "${rows[@]}"
  echo "};"
} >build/proofs.h

# 2. Host build (Linux: the hidraw backend), and the self-test against the Android goldens.
cc "${CFLAGS[@]}" -O2 -o build/pq1-demo pq1-demo.c
build/pq1-demo --selftest "$ANDROID/test/resources/golden"

# 3. The two macOS binaries. zig's linker ad-hoc signs arm64, which Apple Silicon requires.
"$ZIG" cc "${CFLAGS[@]}" -Os -s -target aarch64-macos.11.0 -o build/pq1-demo-arm64 pq1-demo.c
"$ZIG" cc "${CFLAGS[@]}" -Os -s -target x86_64-macos.11.0 -o build/pq1-demo-x86_64 pq1-demo.c

# 4. A bash header that unpacks the binary for this Mac into $TMPDIR once, then runs it.
id=$(cat build/pq1-demo-arm64 build/pq1-demo-x86_64 | { sha256sum 2>/dev/null || shasum -a 256; } | cut -c1-12)
out="dist/PQ1 Demo.command"
{
  sed "s/@ID@/$id/" <<'EOF'
#!/bin/bash
# PQ1 Demo: double-click to open it in Terminal, then plug in PQ1 and unlock it with its PIN.
# This file carries the program for Apple Silicon and Intel Macs. Nothing is installed.
case "$(uname -m)" in
  arm64 | x86_64) arch=$(uname -m) ;;
  *) echo "PQ1 Demo does not run on this Mac ($(uname -m))."; exit 1 ;;
esac
dir="${TMPDIR:-/tmp}/pq1-demo-@ID@"
bin="$dir/pq1-demo-$arch"
if [ ! -x "$bin" ]; then
  mkdir -p "$dir" &&
    sed -n "/^#BEGIN $arch\$/,/^#END $arch\$/p" "$0" | sed '1d;$d' | base64 --decode >"$bin.$$" &&
    chmod +x "$bin.$$" && mv -f "$bin.$$" "$bin" || { echo "PQ1 Demo: could not unpack itself."; exit 1; }
fi
caffeinate -di -w $$ & # keep the display on while the demo runs
exec "$bin"
exit 1
EOF
  for arch in arm64 x86_64; do
    echo "#BEGIN $arch"
    base64 <"build/pq1-demo-$arch" | tr -d '\n' | fold -w 76
    echo
    echo "#END $arch"
  done
} >"$out"
chmod +x "$out"

# 5. A zip keeps the executable bit (a bare .command downloaded by a browser loses it).
cp README.txt "dist/Read me.txt"
rm -f dist/PQ1-Demo-macOS.zip
(cd dist && zip -q -X PQ1-Demo-macOS.zip "PQ1 Demo.command" "Read me.txt")
ls -l build/pq1-demo-arm64 build/pq1-demo-x86_64 "$out" dist/PQ1-Demo-macOS.zip

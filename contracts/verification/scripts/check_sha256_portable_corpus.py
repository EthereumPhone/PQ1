#!/usr/bin/env python3
"""Execute the authenticated Rust word body and check the committed Lean corpus.

The temporary module appends a visibility wrapper; it preserves every original
source byte. These finite cases supplement, and do not replace, compression_spec.
"""
from __future__ import annotations

import argparse
import os
from pathlib import Path
import pwd
import subprocess
import tempfile

from check_sha256_portable_source import ROOT, VENDOR, check

VECTORS = ROOT / "contracts/verification/extracted/Extracted/Sha256Portable/DiffVectors.lean"
RUST_MAIN = r'''
#![allow(dead_code)]
mod consts;
mod soft;
use std::io::{self, Read};
fn main() {
    let mut text = String::new();
    io::stdin().read_to_string(&mut text).unwrap();
    for line in text.lines() {
        let words: Vec<u32> = line.split_whitespace().map(|x| x.parse().unwrap()).collect();
        assert_eq!(words.len(), 24);
        let mut state: [u32; 8] = words[..8].try_into().unwrap();
        let block: [u32; 16] = words[8..].try_into().unwrap();
        soft::proof_corpus_word(&mut state, &block);
        println!("{}", state.map(|x| x.to_string()).join(" "));
    }
}
'''
WRAPPER = b'''
// Test-only access to the unchanged private word-compression body above.
pub fn proof_corpus_word(state: &mut [u32; 8], block: &[u32; 16]) {
    sha256_digest_block_u32(state, block);
}
'''


def cases() -> list[list[int]]:
    mask = 2**32 - 1
    patterns = [0, 1, mask, 0x80000000, 0x7fffffff, 0x55555555, 0xaaaaaaaa]
    rows = [[x] * 24 for x in patterns] + [[i for i in range(24)]]
    for value in [1, 0x80000000, mask]:
        for index in range(24):
            row = [0] * 24
            row[index] = value
            rows.append(row)
    # Fixed integer recurrence, independent of Python's random implementation.
    seed = 0x243f6a88
    for _ in range(32):
        row = []
        for _ in range(24):
            seed ^= (seed << 13) & mask
            seed ^= seed >> 17
            seed ^= (seed << 5) & mask
            row.append(seed)
        rows.append(row)
    assert len(rows) == 112 and len({tuple(x) for x in rows}) == 112
    return rows


def rust_outputs(rows: list[list[int]]) -> list[list[int]]:
    errors = check()
    if errors:
        raise RuntimeError("; ".join(errors))
    with tempfile.TemporaryDirectory(prefix="pq-sha256-corpus-") as tmp:
        root = Path(tmp)
        (root / "consts.rs").write_bytes((ROOT / VENDOR / "src/consts.rs").read_bytes())
        (root / "soft.rs").write_bytes((ROOT / VENDOR / "src/sha256/soft.rs").read_bytes() + WRAPPER)
        (root / "main.rs").write_text(RUST_MAIN)
        rustc = Path(pwd.getpwuid(os.getuid()).pw_dir) / ".cargo/bin/rustc"
        subprocess.run([str(rustc), "--edition=2021", "--target=x86_64-unknown-linux-gnu",
                        "-C", "opt-level=2", "-C", "overflow-checks=on",
                        str(root / "main.rs"), "-o", str(root / "corpus")],
                       cwd=ROOT, check=True, timeout=120)
        result = subprocess.run([str(root / "corpus")], check=True, capture_output=True,
                                text=True, timeout=30,
                                input="\n".join(" ".join(map(str, row)) for row in rows) + "\n")
    outputs = [[int(x) for x in line.split()] for line in result.stdout.splitlines()]
    if len(outputs) != len(rows) or any(len(row) != 8 or any(x < 0 or x >= 2**32 for x in row)
                                       for row in outputs):
        raise RuntimeError("Rust corpus output inventory/range changed")
    return outputs


def render(rows: list[list[int]], outputs: list[list[int]]) -> str:
    def arr(row):
        return "#[" + ", ".join(map(str, row)) + "]"
    body = ",\n".join("  (" + arr(row[:8]) + ", " + arr(row[8:]) + ", " + arr(output) + ")"
                       for row, output in zip(rows, outputs, strict=True))
    return ("-- Generated by scripts/check_sha256_portable_corpus.py --generate.\n"
            "-- Expected outputs execute the authenticated, unchanged Rust word body.\n"
            "namespace Sha256PortableDiff\n"
            "def vectors : List (Array UInt32 × Array UInt32 × Array UInt32) := [\n"
            + body + "\n]\nend Sha256PortableDiff\n")


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--generate", action="store_true")
    args = parser.parse_args()
    rows = cases()
    expected = render(rows, rust_outputs(rows))
    if args.generate:
        VECTORS.write_text(expected)
    elif VECTORS.read_text() != expected:
        raise RuntimeError("Rust word-compression corpus differs from committed Lean vectors")
    print("OK: 112 executed Rust word-compression cases match the Lean corpus")


if __name__ == "__main__":
    main()

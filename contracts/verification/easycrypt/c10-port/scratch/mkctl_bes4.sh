#!/usr/bin/env bash
# PROMOTED 2026-09-14.  Mutation specs below are copied VERBATIM, by script, from
#   experiments/wots-badenc/red/mkctl4.sh
# -- only source/output paths changed.  scratch/check_tcoll_ctls_match.py then
# checks every generated control against the experiment's own control by
# comment-stripped equality, so a porting slip is CAUGHT rather than trusted.
# Generate the SEVEN MUST-FAIL controls (the experiment comment said "five"; it generates seven) for BadEncStep4.ec.  Each deletes exactly
# ONE piece of information and leaves every intro arity unchanged, so a control
# that COMPILES would mean the deleted fact is not load-bearing and the evidence
# in BadEncStep4.ec is worthless.
set -eu
cd "$(dirname "$0")/.."
python3 - <<'PY'
import re
src = open('cdrafts-split/BadEncStep4.ec').read()

def emit(name, s, note):
    assert s != src, name + ": replacement did not fire"
    open('scratch/bes4_ctl%s.ec' % name[-1], 'w').write(
        "(* MUST-FAIL CONTROL for cdrafts-split/BadEncStep4.ec -- %s\n"
        "   Generated by scratch/mkctl_bes4.sh.  If this COMPILES the evidence is worthless. *)\n" % note
        + s)

# CtlA -- s4_transfer's `c <= p_tgts` premise deleted.
emit('S4CtlA', src.replace(
  """      (wads : wadrs list) (i : int) (mA : dgstblock) (ctrA : cntr) :
     c <= p_tgts""",
  """      (wads : wadrs list) (i : int) (mA : dgstblock) (ctrA : cntr) :
     true""", 1),
  "s4_transfer without `c <= p_tgts`; must fail at `size ts <= p_tgts`")

# CtlB -- s4_transfer's `s4_ts_enc ts` premise deleted.
emit('S4CtlB', src.replace(
  """  => s4_wads_ts wads ts
  => s4_ts_enc ts
  => (   size qs <= c""",
  """  => s4_wads_ts wads ts
  => true
  => (   size qs <= c""", 1),
  "s4_transfer without `s4_ts_enc ts`; must fail at `e = e'`")

# CtlC -- s4_transfer's `s4_wads_ts wads ts` premise deleted.
emit('S4CtlC', src.replace(
  """  => s4_qs_ts qs ts
  => s4_wads_ts wads ts
  => s4_ts_enc ts""",
  """  => s4_qs_ts qs ts
  => true
  => s4_ts_enc ts""", 1),
  "s4_transfer without `s4_wads_ts wads ts`; must fail at the common tweak")

# CtlD -- the grind while-invariant's head/filter conjunct deleted.
emit('S4CtlD', src.replace(
  """    /\\ (!found{1} =>
          head witness
            (filter (fun (cc : cntr) =>
                       predC (ThC FC.O_THFC_Default.pp{1} ad{1} m{1} cc)) cs{1})
          = grindC FC.O_THFC_Default.pp{1} ad{1} m{1}))""",
  """    /\\ true)""", 1),
  "grind invariant without the head/filter conjunct; must fail in query_eq_badenc")

# CtlE -- the seq assertion's `em{1} = em{2}` deleted.
emit('S4CtlE', src.replace(
  """  /\\ c{1} = c{2}
  /\\ em{1} = em{2}
  /\\ em{1} = encode_msgWOTS m0{1}
  /\\ sk{1} = [] /\\ sig{1} = []""",
  """  /\\ c{1} = c{2}
  /\\ true
  /\\ em{1} = encode_msgWOTS m0{1}
  /\\ sk{1} = [] /\\ sig{1} = []""", 1),
  "coupling without `em{1} = em{2}`; must fail in the chain loops")

# CtlF -- s4_transfer's `s4_qs_ts qs ts` premise deleted.
emit('S4CtlF', src.replace(
  """     c <= p_tgts
  => s4_qs_ts qs ts""",
  """     c <= p_tgts
  => true""", 1),
  "s4_transfer without `s4_qs_ts qs ts`; must fail")

# CtlG -- NECESSITY control on a PROOF STEP (not an information deletion):
# the `s4_transfer` instance is removed from badenc_le_tcoll's closing step.
# If this COMPILES, `s4_transfer` is decoration and controls A-C/F say nothing
# about the headline bound.
emit('S4CtlG', src.replace(
  """have := s4_transfer psL qs_L ts_R wads_L rR.`1 rR.`2 rR.`3.`2
          le_c_ptgts hqt hwt hte hpre.
smt().""",
  """smt().""", 1),
  "badenc_le_tcoll without the s4_transfer instance; must fail")

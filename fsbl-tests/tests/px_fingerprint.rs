//! FSBL pixel-UI fingerprint (`px-fingerprint`): the generated assets are
//! current, and the FSBL's composer paints exactly what the pixel-UI engine
//! paints.
//!
//! `fsbl/src/px_fprint_assets.rs` is generated HERE from the engine and the
//! baked atlas the secure world uses. After a font, layout or title change:
//!
//!     PQ1_BLESS=1 cargo test -p pqsigner-fsbl-tests --test px_fingerprint
//!
//! The FSBL module is compiled into this host test unchanged (`#[path]`).

#[allow(dead_code)]
#[path = "../../fsbl/src/px_fprint.rs"]
mod px_fprint;

use std::fmt::Write as _;

use pqsigner_ui_px::font::{Font, TierId};
use pqsigner_ui_px::png::render_full;
use pqsigner_ui_px::pq1a::{self, Atlas};
use pqsigner_ui_px::raster::{blend_over, render_strip, Frame, Rgb, Strip, H, W};
use pqsigner_ui_px::rows::{self, WORDS_COLS, WORDS_ROWS};
use pqsigner_ui_px::scene::Anim;
use pqsigner_ui_px::{Icon, ResultMark, Screen, ScreenBuilder, State};
use sphincs_tz_bip39::WORDLIST;

const ATLAS: &[u8] = include_bytes!("../../nonsecure/assets/ui-px/atlas.pq1a");
const ASSETS_PATH: &str = concat!(env!("CARGO_MANIFEST_DIR"), "/../fsbl/src/px_fprint_assets.rs");

/// The grid's tier (`rows::build_words`).
const TIER: TierId = TierId::regular(22);
/// `rows::NUM_ALPHA` (private there; the pixel-exact test pins it).
const NUM_ALPHA: u8 = 128;
/// Glyph table: `a..=z`, then `1..=8`.
const GLYPH_CHARS: &[u8] = b"abcdefghijklmnopqrstuvwxyz12345678";

fn font() -> Font<'static> {
    let atlas = Atlas::parse(ATLAS).expect("atlas.pq1a parses");
    Font::parse(atlas.entry(pq1a::NAME_FONTS).expect("fonts entry")).expect("font atlas")
}

fn title_screen() -> Screen {
    // `secure/src/ui/px/status_map.rs`, "OS Fingerprint".
    ScreenBuilder::status(b"OSFPRINT", Icon::Fingerprint, b"OS FINGERPRINT", State::None, ResultMark::None)
        .finish()
        .expect("title screen")
}

/// The settled title frame in wire order (column by column, `H - 1 - y`).
fn title_wire() -> Vec<u16> {
    let atlas = Atlas::parse(ATLAS).expect("atlas");
    let font = font();
    let marks = atlas.marks();
    let s = title_screen();
    let settled = |until: u32| {
        let mut anim = Anim::new(&s, 0, 0);
        let mut t = 16;
        while t < until {
            anim.step(t);
            t += 16;
        }
        render_full(&anim, &marks, &font)
    };
    let frame = settled(4_000);
    assert_eq!(frame, settled(8_000), "the title screen must be settled by 4 s");
    let (w, h) = (W as usize, H as usize);
    let mut wire = Vec::with_capacity(w * h);
    for x in 0..w {
        for i in 0..h {
            wire.push(frame[(h - 1 - i) * w + x]);
        }
    }
    wire
}

fn baseline(font: &Font, y: i32) -> i32 {
    // `font::blit_run`, `baseline: false` (vertical centre).
    let t = font.tier(TIER).expect("tier 22");
    y + ((i32::from(t.ascent_q6) - i32::from(t.descent_q6)) / 2 + 32) / 64
}

fn generate() -> String {
    let font = font();
    let tier = font.tier(TIER).expect("tier 22");
    let mut o = String::new();
    o.push_str(
        "//! GENERATED by `fsbl-tests/tests/px_fingerprint.rs` from the pixel-UI\n\
         //! engine and `nonsecure/assets/ui-px/atlas.pq1a`. Do not edit; regenerate\n\
         //! with `PQ1_BLESS=1 cargo test -p pqsigner-fsbl-tests --test px_fingerprint`.\n\n",
    );

    // Title: palette + run-length tokens over the wire-order frame.
    let wire = title_wire();
    let mut palette: Vec<u16> = Vec::new();
    let mut rle: Vec<u8> = Vec::new();
    let mut i = 0;
    while i < wire.len() {
        let c = wire[i];
        let mut n = 1;
        while i + n < wire.len() && wire[i + n] == c && n < 259 {
            n += 1;
        }
        let idx = palette.iter().position(|&p| p == c).unwrap_or_else(|| {
            palette.push(c);
            palette.len() - 1
        });
        assert!(idx < 64, "title palette exceeds 64 colours");
        if n <= 3 {
            rle.push(((n as u8 - 1) << 6) | idx as u8);
        } else {
            rle.push(0xC0 | idx as u8);
            rle.push((n - 4) as u8);
        }
        i += n;
    }
    writeln!(o, "pub static TITLE_PALETTE: [u16; {}] = {:?};", palette.len(), palette).unwrap();
    writeln!(o, "pub static TITLE_RLE: [u8; {}] = {:?};\n", rle.len(), rle).unwrap();

    // Glyphs.
    let mut bits: Vec<u8> = Vec::new();
    let mut table = Vec::new();
    for &c in GLYPH_CHARS {
        let g = tier.glyph(c).expect("glyph baked");
        let off = u16::try_from(bits.len()).expect("glyph offset fits u16");
        bits.extend_from_slice(g.rows);
        table.push((g.w, g.h, g.bearing_x, g.bearing_top, g.advance_q6, off));
    }
    writeln!(o, "/// `(w, h, bearing_x, bearing_top, advance_q6, bitmap offset)` for `a..=z`, `1..=8`.").unwrap();
    writeln!(o, "pub static GLYPHS: [(u8, u8, i8, i8, u16, u16); {}] = {:?};", table.len(), table).unwrap();
    writeln!(o, "pub static GLYPH_BITS: [u8; {}] = {:?};\n", bits.len(), bits).unwrap();

    // Grid geometry: numbers are static, words are laid out at run time.
    let mut numbers = Vec::new();
    for k in 0..8usize {
        let ((nx, y), _) = rows::grid_cell(k);
        let text = rows::grid_number(1, k);
        assert_eq!(text.len(), 1, "single-digit grid numbers");
        let gi = GLYPH_CHARS.iter().position(|&c| c == text[0]).expect("digit glyph");
        let g = tier.glyph(text[0]).expect("digit");
        let x_q6 = (nx << 6) - i32::from(g.advance_q6);
        let gx = ((x_q6 + 32) >> 6) + i32::from(g.bearing_x);
        let gy = baseline(&font, y) - i32::from(g.bearing_top);
        numbers.push((gi as u8, gx as i16, gy as i16));
    }
    let word_baseline: Vec<i16> = WORDS_ROWS.iter().map(|&y| baseline(&font, y) as i16).collect();
    let word_x: Vec<i16> = WORDS_COLS.iter().map(|&(_, wx)| wx as i16).collect();
    writeln!(o, "/// `(glyph, x, y)` of grid numbers 1..=8.").unwrap();
    writeln!(o, "pub static NUMBERS: [(u8, i16, i16); 8] = {numbers:?};").unwrap();
    writeln!(o, "pub static WORD_BASELINE: [i16; 4] = {word_baseline:?};").unwrap();
    writeln!(o, "pub static WORD_X: [i16; 2] = {word_x:?};\n").unwrap();

    // Colours: the glyph LUT over black at full run alpha (`font::blit_run`).
    let word = Rgb::WHITE;
    let num = Rgb::WHITE.scale(NUM_ALPHA);
    let lut = |c: Rgb| -> Vec<u16> { (0..16u16).map(|n| blend_over(0, c, (n * 17) as u8)).collect() };
    writeln!(o, "pub static WORD_RGB: [u8; 3] = {:?};", [word.r, word.g, word.b]).unwrap();
    writeln!(o, "pub static NUM_RGB: [u8; 3] = {:?};", [num.r, num.g, num.b]).unwrap();
    writeln!(o, "pub static WORD_OVER_BLACK: [u16; 16] = {:?};", lut(word)).unwrap();
    writeln!(o, "pub static NUM_OVER_BLACK: [u16; 16] = {:?};\n", lut(num)).unwrap();

    // Word suffixes past the fifth letter.
    let mut acc: Vec<bool> = Vec::new();
    for w in WORDLIST.iter() {
        let extra = &w.as_bytes()[w.len().min(5)..];
        assert!(extra.len() <= 3, "BIP-39 English words have at most eight letters");
        for b in (0..2).rev() {
            acc.push((extra.len() >> b) & 1 == 1);
        }
        for &c in extra {
            let v = c - b'a';
            for b in (0..5).rev() {
                acc.push((v >> b) & 1 == 1);
            }
        }
    }
    let suffix: Vec<u8> = acc
        .chunks(8)
        .map(|c| c.iter().enumerate().fold(0u8, |v, (i, &b)| v | (u8::from(b) << (7 - i))))
        .collect();
    writeln!(o, "/// Per word: 2-bit count of letters past the fifth, then 5 bits each.").unwrap();
    writeln!(o, "pub static SUFFIX_BITS: [u8; {}] = {:?};", suffix.len(), suffix).unwrap();
    o
}

#[test]
fn px_fprint_assets_are_current() {
    let fresh = generate();
    if std::env::var_os("PQ1_BLESS").is_some() {
        std::fs::write(ASSETS_PATH, &fresh).expect("write assets");
        return;
    }
    let on_disk = std::fs::read_to_string(ASSETS_PATH).unwrap_or_default();
    assert!(
        on_disk == fresh,
        "fsbl/src/px_fprint_assets.rs is stale: PQ1_BLESS=1 cargo test -p pqsigner-fsbl-tests --test px_fingerprint"
    );
}

#[test]
fn title_decodes_to_the_engine_frame() {
    let wire = title_wire();
    let mut t = px_fprint::Title::new();
    let mut col = [0u16; px_fprint::H];
    for x in 0..px_fprint::W {
        t.next_column(&mut col);
        assert_eq!(&col[..], &wire[x * px_fprint::H..(x + 1) * px_fprint::H], "title column {x}");
    }
}

#[test]
fn every_word_decodes_whole() {
    for (i, w) in WORDLIST.iter().enumerate() {
        let got = px_fprint::full_word(i as u16, sphincs_tz_bip39::word_prefix_at(i as u16));
        let n = got.iter().position(|&b| b == 0).unwrap_or(got.len());
        assert_eq!(&got[..n], w.as_bytes(), "word {i}");
    }
}

/// Engine render of the grid exactly as the secure world builds it
/// (`status_map::fingerprint_grid` → `rows::build_words`), minus the
/// layout's corner chevrons, in wire order.
fn engine_grid(words: &[&[u8]; 8]) -> Vec<u16> {
    let font = font();
    let s = ScreenBuilder::words(b"FPRINT", b"", words).finish().expect("grid");
    let mut frame = Frame::new();
    rows::build_words(&s, 255, &mut frame);
    let mut buf = vec![0u16; (W * H) as usize];
    let mut strip = Strip::new(0, W, &mut buf).expect("strip");
    render_strip(&frame, &font, &mut strip);
    buf
}

fn fsbl_grid(words: &[&[u8]; 8]) -> Vec<u16> {
    let mut cells = [[0u8; px_fprint::WORD_LEN]; 8];
    for (cell, w) in cells.iter_mut().zip(words) {
        cell[..w.len()].copy_from_slice(w);
    }
    let g = px_fprint::Grid::new(&cells);
    let mut out = Vec::with_capacity(px_fprint::W * px_fprint::H);
    let mut col = [0u16; px_fprint::H];
    for x in 0..px_fprint::W {
        g.column(x, &mut col);
        out.extend_from_slice(&col);
    }
    out
}

fn assert_grid_matches(words: &[&[u8]; 8]) {
    let (a, b) = (engine_grid(words), fsbl_grid(words));
    if let Some(i) = a.iter().zip(&b).position(|(x, y)| x != y) {
        panic!(
            "{:?}: first difference at x={} y={} engine {:#06x} fsbl {:#06x}",
            words.map(|w| String::from_utf8_lossy(w).into_owned()),
            i / px_fprint::H,
            px_fprint::H - 1 - i % px_fprint::H,
            a[i],
            b[i]
        );
    }
}

#[test]
fn grid_matches_the_engine_pixel_for_pixel() {
    // Every word of the list once, eight at a time, so every glyph pair that
    // occurs in a real word is composed at least once in both columns.
    let all: Vec<&[u8]> = WORDLIST.iter().map(|w| w.as_bytes()).collect();
    for chunk in all.chunks(8) {
        let words: [&[u8]; 8] = core::array::from_fn(|i| chunk[i % chunk.len()]);
        assert_grid_matches(&words);
    }
    // The widest words in every cell.
    let long: Vec<&[u8]> = all.iter().copied().filter(|w| w.len() == 8).collect();
    for chunk in long.chunks(8) {
        let words: [&[u8]; 8] = core::array::from_fn(|i| chunk[i % chunk.len()]);
        assert_grid_matches(&words);
    }
}

#[test]
fn the_dev_unit_release_words_render() {
    // `RELEASE.txt` of dev-unit 26.10.21.1, slot A.
    let words: [&[u8]; 8] = [b"sound", b"then", b"action", b"pride", b"cover", b"foster", b"dove", b"select"];
    assert_grid_matches(&words);
    assert!(fsbl_grid(&words).iter().filter(|&&p| p != 0).count() > 1_000);
}

#!/usr/bin/env python3
"""wallet_bench_sign.py — signatures for test/gas/C10WalletGasBench.t.sol (#1155 gas track).

Reads the three SIGNING-INPUT values printed by `forge test --match-test test_print_signing_inputs
-vv` (stdin), signs them with the Python references and writes
contracts/smart-wallet/test/gas/c10_wallet_bench_vectors.json:
  v1_1271_sig : v1 signature (clean-room independent_c10_signer.py, the key of
                test/c10_test_vectors.json) over walletV1's EIP-1271 nested hash;
  v2_userop_sig, v2_1271_sig : v2 DRAFT 0.3 signatures (c10v2_ref.py, KAT key 0) over the userOp
                sphincsDigest and over walletV2's nested hash.
Each signature is verified by the same reference before it is written.
"""
import json
import os
import re
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.abspath(os.path.join(HERE, "..", ".."))
sys.path.insert(0, os.path.join(HERE, "..", "c10-autoresearch", "c10v2"))
sys.path.insert(0, os.path.join(ROOT, "contracts", "verification", "scripts"))
import c10v2_ref as v2  # noqa: E402
import independent_c10_signer as v1  # noqa: E402

log = sys.stdin.read()
vals = {}
for name in ("v1-1271-nested", "v2-1271-nested", "userop-digest"):
    m = re.search(r"SIGNING-INPUT " + re.escape(name) + r"\s+(0x[0-9a-fA-F]{64})", log)
    assert m, f"missing {name} in the forge log"
    vals[name] = bytes.fromhex(m.group(1)[2:])

kat = json.load(open(os.path.join(ROOT, "contracts/smart-wallet/test/c10v2_kat_vectors.json")))
v2.configure(())
sk2, ps2 = v2.kat_key(0)
root2 = bytes.fromhex(kat["v0"]["pkRoot"][2:])[:16]
assert v2.keygen(sk2, ps2) == root2 and ps2 == bytes.fromhex(kat["v0"]["pkSeed"][2:])[:16]

root1 = v1.compute_pk_root(v1._SK_SEED, v1._PK_SEED)
assert root1 == v1._EXPECTED_PK_ROOT

out = {"_comment": "generated by research/c10-gas/wallet_bench_sign.py; do not edit by hand"}
s = v1.sign(v1._SK_SEED, v1._PK_SEED, root1, vals["v1-1271-nested"])
assert v1.verify(v1._PK_SEED, root1, vals["v1-1271-nested"], s)
out["v1_1271_nested"] = "0x" + vals["v1-1271-nested"].hex()
out["v1_1271_sig"] = "0x" + s.hex()
for key, name in (("v2_userop", "userop-digest"), ("v2_1271", "v2-1271-nested")):
    s = v2.sign(sk2, ps2, root2, vals[name])
    assert v2.verify(ps2, root2, vals[name], s)
    out[key + "_sig"] = "0x" + s.hex()
out["v2_1271_nested"] = "0x" + vals["v2-1271-nested"].hex()
out["userop_digest"] = "0x" + vals["userop-digest"].hex()
dst = os.path.join(ROOT, "contracts/smart-wallet/test/gas/c10_wallet_bench_vectors.json")
json.dump(out, open(dst, "w"), indent=1)
print("wrote", dst)

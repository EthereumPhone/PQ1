#!/usr/bin/env python3
"""
v1_trace_export.py — per-primitive trace vectors for the deployed C10 v1 verifier (#1155 gas
track), the v1 counterpart of v2_trace_export.py.

Runs the clean-room v1 verifier (contracts/verification/scripts/independent_c10_signer.py)
over the four valid vectors in test/c10_test_vectors.json and records every SHA-256 input in
call order, labelled with its role and decoded 32-byte ADRS. That clean-room verify has no
WOTS+C digit-sum check (the Yul does), so only valid vectors are exported; for them the two
SHA-256 call sequences coincide (361 calls).

Run (from the repo root):
  python3 research/c10-gas/v1_trace_export.py contracts/smart-wallet/test/c10_test_vectors.json \
      contracts/smart-wallet/test/gas/c10v1_trace_vectors.json
"""
import json
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, os.path.join(HERE, "..", "..", "contracts", "verification", "scripts"))
import independent_c10_signer as ref  # noqa: E402

ROLE = {96: "th", 128: "th_pair|wots_digest", 160: "h_msg", 480: "th_multi13", 1440: "th_multi43"}


def label(inp):
    a = int.from_bytes(inp[32:64], "big")
    f = [(a >> s) & m for s, m in ((224, 0xFFFFFFFF), (160, 0xFFFFFFFFFFFFFFFF), (128, 0xFFFFFFFF),
                                   (96, 0xFFFFFFFF), (64, 0xFFFFFFFF), (32, 0xFFFFFFFF), (0, 0xFFFFFFFF))]
    if len(inp) == 160:
        return "h_msg"
    return (f"{ROLE.get(len(inp), 'len' + str(len(inp)))} layer={f[0]} tree={f[1]} type={f[2]} kp={f[3]} "
            f"ci={f[4]} cp={f[5]} ha={f[6]}")


def trace(pk_seed, pk_root, msg, sig):
    calls = []
    orig = ref.sha256

    def rec(b):
        calls.append(bytes(b))
        return orig(b)

    ref.sha256 = rec
    try:
        ok = ref.verify(pk_seed, pk_root, msg, sig)
    finally:
        ref.sha256 = orig
    return ok, calls


def main(src, dst):
    d = json.load(open(src))
    res = {"_comment": "generated by research/c10-gas/v1_trace_export.py from " + os.path.basename(src)
           + "; do not edit by hand", "keys": []}
    for i, v in enumerate(d["vectors"]):
        if not v["expectValid"]:
            continue
        ps = bytes.fromhex(v["pkSeed"][2:])[:16]
        pr = bytes.fromhex(v["pkRoot"][2:])[:16]
        m = bytes.fromhex(v["message"][2:])
        sig = bytes.fromhex(v["signature"][2:])
        ok, calls = trace(ps, pr, m, sig)
        assert ok and len(calls) == 361, (v["label"], ok, len(calls))
        k = f"vec{i}"
        res[k] = {"label": v["label"], "accept": ok, "count": len(calls),
                  "inputs": ["0x" + c.hex() for c in calls], "labels": [label(c) for c in calls]}
        res["keys"].append(k)
        print(f"{k} ({v['label']}): {len(calls)} SHA-256 inputs, accept={ok}", file=sys.stderr)
    json.dump(res, open(dst, "w"), indent=1)


if __name__ == "__main__":
    main(sys.argv[1], sys.argv[2])

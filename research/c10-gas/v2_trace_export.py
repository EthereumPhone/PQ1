#!/usr/bin/env python3
"""
v2_trace_export.py — per-primitive gate vectors for the C10 v2 verifier (#1155 gas track).

Runs the Python reference verifier (research/c10-autoresearch/c10v2/c10v2_ref.py, written
from c10v2-spec.md DRAFT 0.3, independent of the Yul) over KAT vectors and records every
SHA-256 input it hashes, in call order, each labelled with its primitive and decoded A7
fields. The forge test test/gas/C10v2PrimitiveTrace.t.sol records the SHA-256 precompile
inputs the on-chain verifier makes for the same vectors and requires the two sequences to be
identical entry by entry, so a divergence is localized to one primitive call.

The reference verify() hashes each WOTS_DIGEST twice in a row (once for the +C check, once
inside wots_pk_from_sig); consecutive identical inputs are collapsed (no two distinct calls
of one verify share an A7, so the collapse cannot hide a real call) and counted.

Run (from the repo root):
  python3 research/c10-gas/v2_trace_export.py contracts/smart-wallet/test/c10v2_kat_vectors.json \
      contracts/smart-wallet/test/gas/c10v2_trace_vectors.json
"""
import json
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, os.path.join(HERE, "..", "c10-autoresearch", "c10v2"))
import c10v2_ref as ref  # noqa: E402

TYPES = {0: "WOTS_HASH", 1: "WOTS_PK", 2: "TREE", 3: "FORS_TREE", 4: "FORS_ROOTS",
         5: "WOTS_PRF", 6: "FORS_PRF", 7: "WOTS_DIGEST", 8: "H_MSG", 9: "FORS_LAST"}
ROLE = {39: "F", 43: "WOTS_DIGEST", 55: "H", 87: "H_MSG", 232: "T_13", 712: "T_43"}


def decode_a7(b7):
    v = int.from_bytes(b7, "big")
    f = {}
    for name in ("type", "layer", "tree", "kp", "ci", "cp", "ha"):
        f[name] = (v >> ref._SHIFT[name]) & ((1 << ref._WIDTH[name]) - 1)
    return f


def label(inp):
    role = ROLE.get(len(inp), f"len{len(inp)}")
    a = inp[16:23] if len(inp) in (232, 712) else inp[-7:]
    f = decode_a7(a)
    t = TYPES.get(f["type"], str(f["type"]))
    return (f"{role} {t} layer={f['layer']} tree={f['tree']} kp={f['kp']} ci={f['ci']} "
            f"cp={f['cp']} ha={f['ha']}")


def trace(pk_seed, pk_root, msg, sig):
    calls = []
    orig = ref.sha256

    def rec(b):
        calls.append(bytes(b))
        return orig(b)

    ref.sha256 = rec
    try:
        ok = ref.verify(pk_seed, pk_root, msg, sig)
    finally:
        ref.sha256 = orig
    out, dups = [], 0
    for c in calls:
        if out and out[-1] == c:
            dups += 1
            continue
        out.append(c)
    return ok, out, dups


def main(src, dst):
    ref.configure(())
    kat = json.load(open(src))
    res = {"_comment": "generated by research/c10-gas/v2_trace_export.py from " + os.path.basename(src)
           + " (spec " + kat.get("spec", "?") + "); do not edit by hand", "keys": []}
    for k in ("v0", "v1", "v2", "v3", "v4", "v5", "n0", "n1", "n2"):
        v = kat[k]
        ps = bytes.fromhex(v["pkSeed"][2:])[:16]
        pr = bytes.fromhex(v["pkRoot"][2:])[:16]
        m = bytes.fromhex(v["message"][2:])
        sig = bytes.fromhex(v["signature"][2:])
        ok, calls, dups = trace(ps, pr, m, sig)
        # n0 stops after H_MSG; n1 after the layer-0 digest; n2 after the layer-1 digest
        exp = {"n0": 1, "n1": 148, "n2": 255}.get(k, 361)
        assert len(calls) == exp, (k, len(calls))
        assert ok == k.startswith("v"), (k, ok)
        assert dups == {"n0": 0, "n1": 0, "n2": 1}.get(k, 2), (k, dups)
        res[k] = {"accept": ok, "count": len(calls), "inputs": ["0x" + c.hex() for c in calls],
                  "labels": [label(c) for c in calls]}
        res["keys"].append(k)
        print(f"{k}: {len(calls)} SHA-256 inputs, accept={ok}, collapsed duplicates={dups}", file=sys.stderr)
    json.dump(res, open(dst, "w"), indent=1)


if __name__ == "__main__":
    main(sys.argv[1], sys.argv[2])

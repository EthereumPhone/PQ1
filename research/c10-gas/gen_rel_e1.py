K = sum(512 ** j for j in range(15))
assert K == 0x40201008040201008040201008040201
M1 = sum(7 * 512 ** k for k in range(15))
M2 = sum(7 * 512 ** k for k in range(14))
assert M1 == 0x1C0E070381C0E070381C0E070381C0E07 and M2 == 0xE070381C0E070381C0E070381C0E07


def lane_extract():
    low, high = [], []
    for k in range(15):
        c = 512 ** k * K
        lo, mid, hi = c % 2 ** 126, (c >> 126) % 512, c >> 135
        assert mid == 1 and c == lo + 2 ** 126 * (mid + 512 * hi)
        low.append(lo)
        high.append(hi)
    V = " + ".join(f"{512 ** k} * l{k}" for k in range(15))
    A = " + ".join(f"{low[k]} * l{k}" for k in range(15) if low[k])
    H = " + ".join(f"{high[k]} * l{k}" for k in range(15) if high[k])
    S = " + ".join(f"l{k}" for k in range(15))
    hyps = "\n    ".join(f"(h{k} : l{k} ≤ {21 if k < 14 else 7})" for k in range(15))
    vs = " ".join(f"l{k}" for k in range(15))
    return f'''/-- **Lane extraction.** Fifteen 9-bit lanes `l_k` (each a sum of at most three 3-bit digits,
    the last of one) packed as `Σ l_k·512^k`, times `K = Σ_{{k<15}} 512^k`, reduced mod `2^256`:
    bits 126..134 hold `Σ l_k` (no lane's prefix sum reaches 512, so nothing carries into lane
    14; the `2^256` truncation only cuts above bit 256). The product is split explicitly as
    `A + 2^126·(Σ l_k + 512·H)` with `A < 2^126` (both by `omega`). -/
theorem lane_extract ({vs} : Nat)
    {hyps} :
    ({V}) * {K} % 2 ^ 256 / 2 ^ 126 % 512 = {S} := by
  have hdec : ({V}) * {K}
      = ({A}) + 2 ^ 126 * (({S}) + 512 * ({H})) := by
    simp only [Nat.add_mul, Nat.mul_assoc]; omega
  have hA : ({A}) < 2 ^ 126 := by omega
  have hS : ({S}) < 512 := by omega
  rw [hdec, show (2:Nat) ^ 256 = 2 ^ 126 * 2 ^ 130 by decide, Nat.mod_mul_right_div_self,
    Nat.mod_mod_of_dvd _ (show 512 ∣ 2 ^ 130 by decide),
    Nat.add_mul_div_left _ _ (by decide : 0 < 2 ^ 126), Nat.div_eq_of_lt hA, Nat.zero_add,
    Nat.add_mul_mod_self_left, Nat.mod_eq_of_lt hS]
'''


def horner(ds):
    """The nested form `simp only [laneLow, …]` produces: 512 * (… (512 * d_last + …)) + d_first."""
    expr = f"d{ds[-1]}"
    for d in reversed(ds[:-1]):
        expr = f"512 * ({expr}) + d{d}"
    return expr


def swar_lanes():
    p1 = horner(list(range(0, 43, 3)))       # digits 0,3,..,42 (15 lanes)
    p2 = horner(list(range(1, 42, 3)))       # digits 1,4,..,40 (14 lanes)
    p3 = horner(list(range(2, 42, 3)))       # digits 2,5,..,41 (14 lanes)
    ds = " ".join(f"d{j}" for j in range(43))
    hyps = "\n    ".join(f"(b{j} : d{j} < 8)" for j in range(43))
    rhs = " + ".join(f"d{j}" for j in range(43))
    lanes = []
    for k in range(15):
        if k < 14:
            lanes.append(f"(d{3*k} + d{3*k+1} + d{3*k+2})")
        else:
            lanes.append("d42")
    vlane = " + ".join(f"{512 ** k} * {lanes[k]}" for k in range(15))
    args = " ".join(lanes)
    bnds = " ".join("(by omega)" for _ in range(15))
    return f'''/-- **The SWAR digit sum on 43 digit variables.** `P1`, `P2`, `P3` are the three masked terms
    in exactly the nested shape the normalization in `swar_digitSum` produces (lane `k` of `P1`
    is digit `3k`, of `P2` digit `3k+1`, of `P3` digit `3k+2`). -/
theorem swar_lanes ({ds} : Nat)
    {hyps} :
    (({p1}) + ({p2}) + ({p3}))
      * {K} % 2 ^ 256 / 2 ^ 126 % 512
      = {rhs} := by
  have hV : ({p1}) + ({p2}) + ({p3}) = {vlane} := by omega
  rw [hV, lane_extract {args} {bnds}]
  omega
'''



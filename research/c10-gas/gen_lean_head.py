#!/usr/bin/env python3
"""Generate the Lean literals for the HEAD (optimized) v1 verifier (#1155 gas track, batch 6).

  SphincsCVerify/Interpreter/C10HeadSource.lean   the assembly interior of
      contracts/smart-wallet/src/verifiers/SPHINCsC10Asm.sol, byte-exact, as a raw string
  SphincsCVerify/Interpreter/C10HeadProgram.lean  the AST literal `c10HeadProgram`, PRINTED BY
      THE LEAN PARSER ITSELF (parseYulFuel over c10HeadSource; research/c10-gas/lean/PrintHead.lean)

`C10HeadParse.lean` (hand-written) then proves `parseYulFuel headFuel c10HeadSource = some
c10HeadProgram` by `rfl` in the kernel. Because the AST literal is produced by the same parser,
that theorem pins the literal to the source (any drift breaks the build); it does NOT add an
independent transcription check (the reference v1 has one: the hand transcription
`c10Program` vs `parse_c10`). The relational proofs consume `c10HeadProgram`.

    python3 research/c10-gas/gen_lean_head.py           # write both files
    python3 research/c10-gas/gen_lean_head.py --check   # exit 1 if either is stale
"""
import os
import pathlib
import re
import subprocess
import sys

ROOT = pathlib.Path(__file__).resolve().parents[2]
SOL = ROOT / "contracts/smart-wallet/src/verifiers/SPHINCsC10Asm.sol"
LEAN = ROOT / "contracts/verification/lean"
SRC_OUT = LEAN / "SphincsCVerify/Interpreter/C10HeadSource.lean"
PROG_OUT = LEAN / "SphincsCVerify/Interpreter/C10HeadProgram.lean"
PRINTER = ROOT / "research/c10-gas/lean/PrintHead.lean"


def interior():
    lines = SOL.read_text().splitlines(keepends=True)
    start = next(i for i, l in enumerate(lines) if l.strip() == "assembly {")
    # the assembly block closes at the first line that is exactly 8 spaces + "}" after start
    end = next(i for i in range(start + 1, len(lines)) if lines[i].rstrip("\n") == "        }")
    body = "".join(lines[start + 1:end])
    if '"#' in body:
        sys.exit("source contains '\"#': cannot embed as a raw string")
    return start + 2, end, body  # 1-based first and last interior line


def source_module():
    first, last, body = interior()
    return f'''/-
SphincsCVerify.Interpreter.C10HeadSource — GENERATED by research/c10-gas/gen_lean_head.py.
Do not edit. RESEARCH (#1155 gas track, batch 6).

`c10HeadSource` is EXACTLY lines {first}-{last} of
`contracts/smart-wallet/src/verifiers/SPHINCsC10Asm.sol` at the optimized (HEAD) v1 — the
interior of the `verify(...)` `assembly {{ ... }}` block — byte-for-byte, as a raw string.
The reference v1 the existing refinement proof is about stays in `C10Source.lean`.
-/

import SphincsCVerify.Interpreter.YulParse

namespace SphincsCVerify.Interpreter.C10

/-- EXACT bytes of the optimized v1's `assembly {{ }}` interior (lines {first}-{last}). -/
def c10HeadSource : String := r#"{body}"#

#guard c10HeadSource.length == {len(body)}   -- ASCII source: chars = bytes

end SphincsCVerify.Interpreter.C10
'''


def program_module():
    env = dict(os.environ, PATH=os.path.expanduser("~/.elan/bin") + ":" + os.environ.get("PATH", ""))
    p = subprocess.run(["lake", "env", "lean", "--tstack=262144", str(PRINTER)], cwd=LEAN, env=env,
                       capture_output=True, text=True)
    out = p.stdout
    m = re.search(r"BEGIN-AST\n(.*)\nEND-AST", out, re.S)
    if p.returncode != 0 or not m:
        sys.exit(f"printer failed (exit {p.returncode}):\n{out[-2000:]}\n{p.stderr[-2000:]}")
    ast = m.group(1)
    n = re.search(r"STMTS (\d+)", out).group(1)
    return f'''/-
SphincsCVerify.Interpreter.C10HeadProgram — GENERATED by research/c10-gas/gen_lean_head.py.
Do not edit. RESEARCH (#1155 gas track, batch 6).

`c10HeadProgram` is the AST the Lean parser (`YulParse.parseYulFuel`) produces for
`c10HeadSource`, printed by research/c10-gas/lean/PrintHead.lean. `parse_c10_head`
(C10HeadParse.lean) re-checks it against the source in the kernel.
-/

import SphincsCVerify.Interpreter.Yul

namespace SphincsCVerify.Interpreter.C10

open SphincsCVerify.Interpreter

/-- The optimized v1 verifier as an AST ({n} top-level statements). -/
def c10HeadProgram : List Stmt :=
{ast}

end SphincsCVerify.Interpreter.C10
'''


def main():
    src = source_module()
    if "--check" in sys.argv:
        ok = SRC_OUT.exists() and SRC_OUT.read_text() == src
        if not ok:
            sys.exit(f"{SRC_OUT} is stale")
        prog = program_module()
        if not PROG_OUT.exists() or PROG_OUT.read_text() != prog:
            sys.exit(f"{PROG_OUT} is stale")
        print("HEAD Lean literals up to date")
        return
    SRC_OUT.write_text(src)
    print(f"wrote {SRC_OUT}")
    env = dict(os.environ, PATH=os.path.expanduser("~/.elan/bin") + ":" + os.environ.get("PATH", ""))
    b = subprocess.run(["lake", "build", "SphincsCVerify.Interpreter.C10HeadSource"], cwd=LEAN, env=env,
                       capture_output=True, text=True)
    if b.returncode != 0:
        sys.exit(f"building C10HeadSource failed:\n{b.stdout[-2000:]}{b.stderr[-2000:]}")
    PROG_OUT.write_text(program_module())
    print(f"wrote {PROG_OUT}")


if __name__ == "__main__":
    main()
